const DICT: Record<Lang, Record<MsgKey, string>> = { zh, en };

let current: Lang = detectLang();

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = DICT[l] ? l : 'en';
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  const s = DICT[current][key] ?? zh[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Follow settings.lang in this context; `onChange` runs after a switch. */
export async function initLang(onChange?: (l: Lang) => void): Promise<void> {
  setLang((await getSettings()).lang);
  onSettingsChanged((s) => {
    if (s.lang === current) return;
    setLang(s.lang);
    onChange?.(s.lang);
  });
}
